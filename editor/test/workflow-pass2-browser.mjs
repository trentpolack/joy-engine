import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile,unlink,readdir,rmdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
import {chromium, expect} from '@playwright/test';
const root = fileURLToPath(new URL('../../../',import.meta.url));
const output = new URL('../../../artifacts/captures/editor-workflow-v2-pass2/',import.meta.url);
await mkdir(output,{recursive:true});
const server = await createServer({configFile:`${root}scripts/development/vite-site.config.mjs`,server:{host:'127.0.0.1',port:0,open:false}});
const fixture = new URL(`../../../projects/luna/assets/workflow-pass2-${process.pid}.formlab`,import.meta.url);
const pillarSource = await readFile(new URL('../../../projects/luna/assets/form/pillar.form',import.meta.url),'utf8');
await writeFile(fixture,JSON.stringify({version:1,name:'Persistence test',source:pillarSource,overrides:{}}),{flag:'wx'});
let browser;
try {
  await server.listen();
  browser = await chromium.launch({executablePath:process.env.CAPTURE_EXECUTABLE,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:1512,height:982}});
  page.setDefaultTimeout(15000);
  await page.addInitScript(() => Object.defineProperty(navigator,'gpu',{value:undefined}));
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = `http://127.0.0.1:${server.httpServer.address().port}`;
  await page.goto(`${base}/editor/?project=vehicle-playground`);
  await page.locator('button[title="assets/playground.joylevel"]').dblclick();
  const level = page.frameLocator('iframe[title="Edit assets/playground.joylevel"]');
  await expect(level.locator('#viewport')).toHaveAttribute('data-ready','true',{timeout:60000});
  const count = await level.locator('#entities .entity-row').count();
  await level.locator('#scene-filter').fill('island');
  await expect(level.locator('#entities .entity-row')).toHaveCount(1);
  await level.locator('#scene-filter').fill('no-such-entity');
  await expect(level.locator('#entities .entity-row')).toHaveCount(0);
  await level.locator('#scene-filter').fill('');
  await expect(level.locator('#entities .entity-row')).toHaveCount(count);
  await level.locator('#entities .entity-row').first().click();
  const position = level.getByLabel('position X',{exact:true});
  const originalPosition = await position.inputValue();
  await position.fill('');
  await position.press('Tab');
  await level.locator('#entities .entity-row').nth(1).click();
  await expect(position).toHaveValue('');
  await expect(position).toHaveAttribute('aria-invalid','true');
  const canvasBox = await level.locator('#viewport').boundingBox();
  await level.locator('#viewport').click({position:{x:canvasBox.width/2,y:canvasBox.height/2}});
  await expect(position).toHaveValue('');
  await position.fill(originalPosition);
  await position.press('Tab');
  await page.screenshot({path:fileURLToPath(new URL('level.png',output))});
  console.log('PASS scene filtering preserves the full authored list');
  await page.goto(`${base}/editor/?project=luna`);
  await page.locator('button[title="assets/form/pillar.form"]').dblclick();
  const form = page.frameLocator('iframe[title="Edit assets/form/pillar.form"]');
  await expect(form.locator('#diagnostic-text')).toContainText('Built successfully',{timeout:60000});
  await expect(form.locator('#override-state')).toContainText('temporary');
  const source = await form.locator('.cm-content').textContent();
  const height = form.getByLabel('height value',{exact:true});
  const initial = await height.inputValue();
  await form.locator('#live').uncheck();
  await height.fill('3');
  await height.press('Tab');
  await form.locator('#property-undo').click();
  await expect(height).toHaveValue(initial);
  await form.locator('#property-redo').click();
  await expect(height).toHaveValue('3');
  await height.fill('');
  await height.press('Tab');
  await expect(height).toHaveValue('');
  await expect(height).toHaveAttribute('aria-invalid','true');
  await expect(form.locator('.numeric-error').first()).toBeVisible();
  await height.fill(initial);
  await height.press('Tab');
  await expect(height).toHaveAttribute('aria-invalid','false');
  assert.equal(await form.locator('.cm-content').textContent(),source,'Raw parameter changes must not rewrite script defaults.');
  await height.press('Shift+ArrowUp');
  await expect(height).toHaveValue(String(Number((Number(initial) + 0.01).toPrecision(12))));
  await height.press('ArrowUp');
  await expect(height).toHaveValue(String(Number((Number(initial) + 0.11).toPrecision(12))));
  await form.locator('#property-undo').click();
  await height.press('Alt+ArrowUp');
  await expect(height).toHaveValue(String(Number((Number(initial) + 1.01).toPrecision(12))));
  await form.locator('#property-undo').click();
  await expect(height).toHaveValue(String(Number((Number(initial) + 0.01).toPrecision(12))));
  const range = form.getByLabel('height',{exact:true});
  const beforeDrag = await height.inputValue();
  const box = await range.boundingBox();
  await page.mouse.move(box.x + box.width*0.45,box.y + box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width*0.6,box.y + box.height/2,{steps:6});
  await range.press('Escape');
  await page.mouse.up();
  await expect(height).toHaveValue(beforeDrag);
  await page.mouse.move(box.x + box.width*0.4,box.y + box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width*0.7,box.y + box.height/2,{steps:8});
  await page.mouse.up();
  assert.notEqual(await height.inputValue(),beforeDrag);
  await form.locator('#property-undo').click();
  await expect(height).toHaveValue(beforeDrag);
  const title = await form.locator('.viewport-title').boundingBox();
  assert.ok(title.height < 65,'Project label must not cover the geometry.');
  await page.screenshot({path:fileURLToPath(new URL('form.png',output))});
  console.log('PASS raw FORM override ownership, property undo/redo and repairable draft');
  await page.goto(`${base}/editor/?project=luna`);
  const fixturePath = `assets/workflow-pass2-${process.pid}.formlab`;
  await page.locator(`button[title="${fixturePath}"]`).dblclick();
  const lab = page.frameLocator(`iframe[title="Edit ${fixturePath}"]`);
  await expect(lab.locator('#diagnostic-text')).toContainText('Built successfully',{timeout:60000});
  await expect(lab.locator('#override-state')).toContainText('saved in this FORM LAB document');
  await lab.getByLabel('height value',{exact:true}).fill('3');
  await lab.getByLabel('height value',{exact:true}).press('Meta+s');
  await expect.poll(async () => JSON.parse(await readFile(fixture,'utf8')).overrides.height).toBe(3);
  await lab.getByLabel('height value',{exact:true}).fill('3.5');
  await lab.getByLabel('height value',{exact:true}).press('Tab');
  await lab.locator('#property-undo').click();
  await expect(lab.getByLabel('height value',{exact:true})).toHaveValue('3');
  await page.reload();
  await page.locator(`button[title="${fixturePath}"]`).dblclick();
  await expect(lab.getByLabel('height value',{exact:true})).toHaveValue('3',{timeout:60000});
  assert.equal(JSON.parse(await readFile(fixture,'utf8')).source,pillarSource);
  await page.screenshot({path:fileURLToPath(new URL('formlab.png',output))});
  console.log('PASS FORM LAB overrides save and reopen without rewriting source');
  console.log('Opening particle document');
  await page.goto(`${base}/editor/?project=space-scuffles`,{waitUntil:'domcontentloaded'});
  console.log('Particle workspace loaded');
  await page.locator('button[title="assets/joyfx/explosion.joyfx"]').dblclick();
  console.log('Particle document clicked');
  const particle = page.frameLocator('iframe[title="Edit assets/joyfx/explosion.joyfx"]');
  const explosion = JSON.parse(await readFile(new URL('../../../projects/space-scuffles/assets/joyfx/explosion.joyfx',import.meta.url),'utf8'));
  await expect(particle.locator('#emitter-list .emitter-item')).toHaveCount(explosion.emitters.length,{timeout:60000});
  await expect(particle.locator('#selected-emitter')).toContainText(explosion.emitters[0].id);
  await expect(particle.locator('#effect-ownership')).toContainText('Whole effect');
  const jsonBefore = await page.locator('#document-state').textContent();
  const durationInput = particle.getByLabel('Duration (s)',{exact:true});
  const initialDuration = await durationInput.inputValue();
  await durationInput.fill('');
  await durationInput.press('Tab');
  await expect(durationInput).toHaveAttribute('aria-invalid','true');
  await particle.locator('[data-action="add-burst"]').click();
  await expect(durationInput).toHaveValue('');
  await particle.locator('#emitter-list button').nth(1).click();
  await expect(particle.locator('#selected-emitter')).toContainText(explosion.emitters[0].id);
  await durationInput.fill(initialDuration);
  await durationInput.press('Tab');
  await expect(durationInput).toHaveAttribute('aria-invalid','false');
  await particle.locator('#replay-window').selectOption('2');
  await expect(particle.locator('#timeline')).toHaveAttribute('max','2');
  await particle.locator('#replay-window').selectOption('custom');
  await particle.locator('#replay-custom').fill('1.5');
  await particle.locator('#replay-custom').press('Tab');
  await expect(particle.locator('#timeline')).toHaveAttribute('max','1.5');
  assert.equal(await page.locator('#document-state').textContent(),jsonBefore,'Replay options must not change exported effect data.');
  await particle.locator('#replay-window').selectOption('full');
  await expect(particle.locator('#timeline')).toHaveAttribute('max','30');
  await expect(particle.locator('#diagnostic')).toHaveAttribute('data-state','live');
  await particle.locator('#play').click();
  await particle.locator('#timeline').evaluate(input => {
    input.value = '0.15';
    input.dispatchEvent(new Event('input',{bubbles:true}));
  });
  await expect(particle.locator('#time')).toHaveText('0.15 s');
  await page.screenshot({path:fileURLToPath(new URL('particles.png',output))});
  await page.setViewportSize({width:1440,height:900});
  await page.screenshot({path:fileURLToPath(new URL('particles-1440.png',output))});
  await page.setViewportSize({width:1800,height:1040});
  await page.screenshot({path:fileURLToPath(new URL('particles-1800.png',output))});
  await writeFile(new URL('index.html',output),'<!doctype html><meta charset="utf-8"><title>Joy Editor workflow v2 pass 2</title><style>body{background:#142132;color:#fff;font:16px Arial}img{max-width:100%}</style>'+['level','form','formlab','particles','particles-1440','particles-1800'].map(name=>`<h2>${name}</h2><img src="${name}.png" alt="${name}">`).join(''));
  assert.deepEqual(errors,[]);
  console.log(`PASS particle ownership and optional replay; captures: ${fileURLToPath(output)}`);
} finally {
  await browser?.close();
  await server.close();
  await unlink(fixture);
  const recovery = new URL('../../../projects/luna/assets/.joy-editor-recovery/',import.meta.url);
  const prefix = fixture.pathname.split('/').at(-1) + '.';
  for(const name of await readdir(recovery).catch(error => {
    if(error.code === 'ENOENT') {
      return [];
    }
    throw error;
  })) {
    if(name.startsWith(prefix)) {
      await unlink(new URL(name,recovery));
    }
  }
  await rmdir(recovery).catch(error => {
    if(!['ENOENT','ENOTEMPTY'].includes(error.code)) {
      throw error;
    }
  });
}
